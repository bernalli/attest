"""Property tests for `attest.views` (plan A11, T3.4).

An example list shares the blind spots of whoever wrote it, so the not-well-
formed coverage here is generated by MUTATION of a well-formed artifact — the
same model `tests/strategies/malformed_manifests.py` already established for
key manifests, reused rather than re-invented, and extended to the three
documents this module builds.

Three properties are asserted across every generated input:

- nothing but `ViewError` ever escapes a builder;
- a mutation that changes an artifact's canonical bytes is REFUSED, never
  silently repaired, truncated or partially accepted;
- a hostile subclass of `dict`/`list`/`str`/`int` never reaches
  canonicalization and never changes the artifact produced.
"""

