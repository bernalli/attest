# --- hostile subclasses (F8, P32) --------------------------------------------


class HostileDict(dict[Any, Any]):
    """A mapping whose every shadowable accessor either lies or explodes."""

    def __iter__(self) -> Any:
        raise AssertionError("a live view object was iterated instead of copied")

    def keys(self) -> Any:
        raise AssertionError("a live view object's keys() was called")

    def items(self) -> Any:
        raise AssertionError("a live view object's items() was called")

    def values(self) -> Any:
        raise AssertionError("a live view object's values() was called")

    def __getitem__(self, key: Any) -> Any:
        raise AssertionError("a live view object was subscripted")

    def get(self, *args: Any, **kwargs: Any) -> Any:
        raise AssertionError("a live view object's get() was called")

    def __len__(self) -> int:
        return 0

    def __eq__(self, other: object) -> bool:
        return True

    __hash__ = object.__hash__


class HostileList(list[Any]):
    def __iter__(self) -> Any:
        raise AssertionError("a live view array was iterated instead of copied")

    def __getitem__(self, index: Any) -> Any:
        raise AssertionError("a live view array was subscripted")

    def __len__(self) -> int:
        return 0

    def __eq__(self, other: object) -> bool:
        return True

    __hash__ = object.__hash__


class HostileStr(str):
    def __str__(self) -> str:
        return "poisoned"

    def __eq__(self, other: object) -> bool:
        return True

    __hash__ = str.__hash__


class HostileInt(int):
    def __int__(self) -> int:
        return 0

    def __eq__(self, other: object) -> bool:
        return True

    __hash__ = int.__hash__


def _hostile(value: Any) -> Any:
    """The same JSON value, every container and scalar replaced by a subclass
    that shadows what `canon.dumps` would otherwise call."""
    if isinstance(value, bool) or value is None:
        return value
    if isinstance(value, dict):
        return HostileDict({_hostile(k): _hostile(v) for k, v in value.items()})
    if isinstance(value, list):
        return HostileList([_hostile(item) for item in value])
    if isinstance(value, str):
        return HostileStr(value)
    if isinstance(value, int):
        return HostileInt(value)
    return value


def _assert_plain(value: Any, where: str) -> None:
    """Every node is of an EXACT plain type — no subclass survived the copy."""
    assert type(value) in (dict, list, str, int, bool, type(None)), (
        f"{where}: {type(value).__name__} reached canonicalization"
    )
    if type(value) is dict:
        for key, item in value.items():
            _assert_plain(key, where)
            _assert_plain(item, where)
    elif type(value) is list:
        for item in value:
            _assert_plain(item, where)


