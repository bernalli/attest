# --- evidence mutations ------------------------------------------------------


def _differs(mutated: object, original: object) -> bool:
    """Did the mutation change the artifact at all?

    A generated "mutation" that happens to reproduce the original is not a
    hostile input, and asserting that it is refused asserts a falsehood. Every
    refusal property below is guarded by this, so a pool that goes stale
    against a new vector shows up as fewer examples, never as a false green.
    """
    try:
        return canon.canonical_bytes(mutated) != canon.canonical_bytes(original)
    except Exception:
        return True


EVIDENCE_MEMBERS: tuple[str, ...] = (
    "entry",
    "leaf_index",
    "tree_size",
    "inclusion_proof",
    "checkpoint",
)


def _hostile_values(evidence: dict[str, Any]) -> dict[str, tuple[object, ...]]:
    """One hostile pool per member, RELATIVE to the evidence being mutated.

    The index pair is why this is a function and not a constant. `tree_size: 1`
    is hostile for evidence whose `leaf_index` is 1 and is the CORRECT value for
    evidence whose `leaf_index` is 0 — a fixed pool written against one vector
    quietly becomes a no-op against another, and a no-op "mutation" asserted to
    be refused is a test asserting a falsehood. Measured: it happened here, on
    the 35a transfer evidence, and only a mutation run surfaced it.
    """
    leaf_index = evidence["leaf_index"]
    tree_size = evidence["tree_size"]
    return {
        "entry": (None, True, 0, "key-manifest", [], {}, {"type": "key-manifest"}),
        "leaf_index": (None, True, -1, "1", [], {}, tree_size, tree_size + 5),
        "tree_size": (None, True, -3, "2", [], {}, leaf_index, leaf_index - 1),
        "inclusion_proof": (
            None,
            True,
            0,
            "ab",
            {},
            [None],
            [""],
            ["zz" * 32],
            ["AB" * 32],
            ["ab" * 32 + "a"],
            ["ab" * 31],
            ["ab" * 32] * (views.MAX_INCLUSION_PROOF_NODES + 1),
        ),
        "checkpoint": (None, True, 0, [], {}),
        "anchors": (None, True, 0, "anchors", []),
    }


@st.composite
def hostile_evidence(draw: st.DrawFn, evidence: dict[str, Any]) -> dict[str, Any]:
    """One evidence member removed, retyped or added — one class per draw."""
    hostile = _hostile_values(evidence)
    mutated = copy.deepcopy(evidence)
    shape = draw(st.sampled_from(("remove", "retype", "extra", "entry")))
    if shape == "remove":
        del mutated[draw(st.sampled_from(EVIDENCE_MEMBERS))]
    elif shape == "retype":
        member = draw(st.sampled_from((*EVIDENCE_MEMBERS, "anchors")))
        mutated[member] = draw(st.sampled_from(hostile[member]))
    elif shape == "extra":
        mutated[draw(st.sampled_from(("proof", "__proto__", "type", "record_sha256")))] = draw(
            st.sampled_from((1, "x", None, {}))
        )
    else:
        entry = dict(mutated["entry"])
        # The entry's members depend on the rail (a `key-manifest` entry carries
        # `manifest_version`, a `transfer-record` entry carries `record_sha256`),
        # so they come from the artifact rather than from a hardcoded list.
        member = draw(st.sampled_from(sorted(entry)))
        if draw(st.booleans()):
            del entry[member]
        else:
            entry[member] = draw(st.sampled_from((None, True, 0, "x", [], {})))
        mutated["entry"] = entry
    return mutated


@PROPERTY_SETTINGS
@given(hostile_evidence(EVIDENCE))
def test_hostile_evidence_is_always_refused(mutated: dict[str, Any]) -> None:
    assume(_differs(mutated, EVIDENCE))
    with pytest.raises(views.ViewError):
        views.build_compromise_claim(copy.deepcopy(MANIFEST), mutated)


@PROPERTY_SETTINGS
@given(st.permutations(sorted(EVIDENCE["entry"])))
def test_permuting_the_entry_members_changes_nothing(order: list[str]) -> None:
    """`entry` is compared as an OBJECT, so member order is not information —
    the claim built from a permuted entry is byte-identical."""
    evidence = copy.deepcopy(EVIDENCE)
    evidence["entry"] = {member: EVIDENCE["entry"][member] for member in order}
    built = views.build_compromise_claim(copy.deepcopy(MANIFEST), evidence)
    assert canon.canonical_bytes(built) == canon.canonical_bytes(CLAIM)


def test_an_empty_inclusion_proof_is_a_shape_the_builder_admits() -> None:
    """A one-leaf tree has an empty proof (vector 35a carries one). The builder
    checks SHAPE; whether the proof actually reconstructs the root is the
    verifier's question, against its own pins."""
    evidence = copy.deepcopy(EVIDENCE)
    evidence["inclusion_proof"] = []
    claim = views.build_compromise_claim(copy.deepcopy(MANIFEST), evidence)
    assert claim["evidence"]["inclusion_proof"] == []


