def _nested(depth: int) -> dict[str, Any]:
    node: dict[str, Any] = {}
    for _ in range(depth - 1):
        node = {"n": node}
    return node


# `canon._serialize` starts the outermost container at depth 1 and refuses a
# container at depth > MAX_DEPTH. `verify._materialize_compromise_view` admits
# each claim at `VIEW_MEMBER_NESTING`, so the containers ABOVE the nested value
# are the claim object and the `evidence` object; the first level of the nested
# chain is `anchors` itself. Deriving this from the position the VERIFIER reads
# is the point: computed from the deeper position instead, the ceiling is one
# level too strict and the producer refuses claims the verifier accepts.
_ANCHOR_DEPTH_CEILING = canon.MAX_DEPTH - canon.VIEW_MEMBER_NESTING - 2


def test_the_claim_depth_ceiling_is_the_one_the_verifier_applies() -> None:
    """The producer must admit exactly what `_materialize_compromise_view`
    admits. A claim at the ceiling is built AND survives the verifier's own
    materializer; one level deeper is refused by both."""
    at_ceiling = copy.deepcopy(EVIDENCE)
    at_ceiling["anchors"] = _nested(_ANCHOR_DEPTH_CEILING)
    claim = views.build_compromise_claim(copy.deepcopy(MANIFEST), at_ceiling)
    assert verify._materialize_compromise_view([claim]) is not None

    over = copy.deepcopy(EVIDENCE)
    over["anchors"] = _nested(_ANCHOR_DEPTH_CEILING + 1)
    with pytest.raises(views.ViewError, match="admissible"):
        views.build_compromise_claim(copy.deepcopy(MANIFEST), over)
    hand_built = {"manifest": copy.deepcopy(MANIFEST), "evidence": over}
    assert verify._materialize_compromise_view([hand_built]) == [None]


def test_claim_depth_ceiling_is_two_sided() -> None:
    at_ceiling = copy.deepcopy(EVIDENCE)
    at_ceiling["anchors"] = _nested(_ANCHOR_DEPTH_CEILING)
    assert views.build_compromise_claim(copy.deepcopy(MANIFEST), at_ceiling)["evidence"]["anchors"]
    over = copy.deepcopy(EVIDENCE)
    over["anchors"] = _nested(_ANCHOR_DEPTH_CEILING + 1)
    with pytest.raises(views.ViewError, match="admissible"):
        views.build_compromise_claim(copy.deepcopy(MANIFEST), over)


# --- the catch-all: only ViewError ever escapes -------------------------------

JSON_VALUES = st.recursive(
    st.none() | st.booleans() | st.integers(-(10**6), 10**6) | st.text(max_size=8),
    lambda children: (
        st.lists(children, max_size=4) | st.dictionaries(st.text(max_size=6), children, max_size=4)
    ),
    max_leaves=12,
)


@PROPERTY_SETTINGS
@given(JSON_VALUES, JSON_VALUES)
def test_only_view_error_escapes_any_builder(first: Any, second: Any) -> None:
    """Arbitrary JSON into every public entry point. A `KeyError`, a
    `TypeError`, a `CanonError` or a `TransparencyError` escaping here would
    make a caller unable to tell "your input is malformed" from "this module
    is broken"."""
    calls = (
        lambda: views.key_manifest_log_entry(first),
        lambda: views.build_compromise_claim(first, second),
        lambda: views.build_compromise_view(first),
        lambda: views.build_transfer_claim(first, second),
        lambda: views.build_transfer_view(first),
        lambda: views.build_revocation_view(first),
        lambda: views.build_revocation_view(first, second),
        lambda: views.claim_capabilities(first, second, None),
        lambda: views.claim_capabilities(first, second, [first]),
    )
    for call in calls:
        try:
            call()
        except views.ViewError:
            pass
