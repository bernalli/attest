_CHAIN_DIRS = [p for p in _LEAF_DIRS if (p / "chain.json").exists()]
_CHAIN_IDS = [str(p.relative_to(VECTORS_DIR)) for p in _CHAIN_DIRS]

# Group 40 (activation witness quorum, v0.2 §11.4) leaves are a THIRD surface
