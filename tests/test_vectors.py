@pytest.mark.parametrize("vector_dir", _VECTOR_DIRS, ids=_VECTOR_IDS)
def test_vector_matches_spec_intended_result(vector_dir: Path) -> None:
    expected = _load_json(vector_dir / "expected.json")
    envelope_bytes = _envelope_bytes(vector_dir)
    trust_store = _trust_store(vector_dir)
    disclosure = _disclosure(vector_dir)
    revocation_view = _revocation_view(vector_dir)

    result = verify.verify(
        envelope_bytes,
        trust_store,
        revocation_view=revocation_view,
        disclosure=disclosure,
        transparency=_transparency_evidence(vector_dir),
        log_keys=_log_keys(vector_dir),
        anchor_policy=_anchor_policy(vector_dir),
        revocation_evidence=_revocation_evidence(vector_dir),
        transfer_view=_transfer_view(vector_dir),
        witness_policy=_witness_policy(vector_dir),
        grant_view=_grant_view(vector_dir),
    )

    assert result.signature == expected["signature"]
    assert result.schema == expected["schema"]
    assert result.trust == expected["trust"]
    if "revocation" in expected:
        assert result.revocation == expected["revocation"]
    if "binding" in expected:
        assert result.binding == expected["binding"]
    if "transparency" in expected:
        assert result.transparency == expected["transparency"]
    if "corroboration" in expected:
        assert result.corroboration == expected["corroboration"]
    if "manifest_freshness" in expected:
        assert result.manifest_freshness == expected["manifest_freshness"]
    if "grant" in expected:
        assert result.grant == expected["grant"]
    if "grant_trust" in expected:
        assert result.grant_trust == expected["grant_trust"]
    if "ok" in expected:
        assert result.ok == expected["ok"]
    if "errors" in expected:
        assert list(result.errors) == expected["errors"]
    if "warnings" in expected:
        assert list(result.warnings) == expected["warnings"]
    for substr in expected.get("errors_contains", []):
        assert any(substr in e for e in result.errors), (
            f"expected an error containing {substr!r}, got {result.errors!r}"
        )
    for substr in expected.get("warnings_contains", []):
        assert any(substr in w for w in result.warnings), (
            f"expected a warning containing {substr!r}, got {result.warnings!r}"
        )


@pytest.mark.parametrize("vector_dir", _TAMPER_DIRS, ids=_TAMPER_IDS)
def test_manifest_tamper_breaks_self_consistency(vector_dir: Path) -> None:
    """Vector 11's second, manifest-level property: the tampered manifest fed
    to `verify()` (in `manifests.json`) no longer self-verifies, while the
    untampered original (`manifest_pristine.json`) does — the concrete
    evidence that "manifest invalid" describes a self-consistency break, not
    just its downstream effect on receipt verification (covered by the
    `signature`/`errors_contains` assertions above)."""
    pristine = _load_json(vector_dir / "manifest_pristine.json")
    trust_data = _load_json(vector_dir / "manifests.json")
    tampered = trust_data["manifests"][pristine["issuer"]]

    assert manifests.verify_key_manifest(pristine) is True
    assert manifests.verify_key_manifest(tampered) is False


def _sole_key_manifest(vector_dir: Path) -> dict[str, Any]:
    """Group 36 only: `audit_chain` takes ONE trusted `key_manifest`, not a
    full `TrustStore` — every group 36 leaf's `manifests.json` trusts
    exactly one issuer, so its sole `"manifests"` value is that manifest."""
    data = _load_json(vector_dir / "manifests.json")
    return next(iter(data["manifests"].values()))


@pytest.mark.parametrize("vector_dir", _CHAIN_DIRS, ids=_CHAIN_IDS)
def test_chain_audit_vectors(vector_dir: Path) -> None:
    """Group 36 (v0.2 §17.5, chain-of-title audit): a SEPARATE surface from
    `verify()` — see this module's docstring for the `chain.json` shape and
    match rules."""
    expected = _load_json(vector_dir / "expected.json")
    chain = _load_json(vector_dir / "chain.json")
    key_manifest = _sole_key_manifest(vector_dir)
    log_keys = _log_keys(vector_dir)
    anchor_policy = _anchor_policy(vector_dir)
    assert log_keys is not None
    assert anchor_policy is not None

    result = transfer.audit_chain(
        chain["payloads"],
        chain["transfer_view"],
        chain["revocation_view"],
        key_manifest,
        log_keys,
        anchor_policy,
    )

    assert result.valid == expected["chain_valid"]
    assert list(result.link_status) == expected["link_status"]
    for substr in expected.get("errors_contains", []):
        assert any(substr in e for e in result.errors), (
            f"expected a chain error containing {substr!r}, got {result.errors!r}"
        )
    assert list(result.warnings) == expected["warnings"]


@pytest.mark.parametrize("vector_dir", _QUORUM_DIRS, ids=_QUORUM_IDS)
def test_witness_quorum_vectors(vector_dir: Path) -> None:
    """Group 40 (v0.2 §11.4, activation-grade witness quorum): a SEPARATE
    surface from `verify()` — see this module's docstring for the
    `witness-quorum.json` shape and match rules. The witness policy is parsed
    here rather than handed over as a document, because this entry point takes
    trusted, already-parsed configuration (unlike `verify()`, which accepts
    either)."""
    expected = _load_json(vector_dir / "expected.json")
    quorum = _load_json(vector_dir / "witness-quorum.json")
    policy = witness.parse_policy(_witness_policy(vector_dir))
    anchor_policy = _anchor_policy(vector_dir)
    assert anchor_policy is not None

    result = witness.evaluate_activation_witness_quorum(
        quorum["checkpoint"],
        witness_policy=policy,
        epoch_id=quorum["epoch_id"],
        expected_origin=quorum["expected_origin"],
        anchor_evidence=quorum["anchor_evidence"],
        anchor_policy=anchor_policy,
        conflict_domain=quorum["conflict_domain"],
    )

    assert result.valid == expected["valid"]
    assert result.witness_time == expected["witness_time"]
    assert list(result.counting_control_groups) == expected["counting_control_groups"]


@pytest.mark.parametrize("vector_dir", _REDEMPTION_DIRS, ids=_REDEMPTION_IDS)
def test_redemption_vectors(vector_dir: Path) -> None:
    """Group 38 (v0.2 §18.7, the audience-bound redemption proof): a FOURTH
    surface, `grant.verify_redemption` rather than `verify()`. There is no
    receipt in the question these leaves ask — only whether this holder proof
    is good for THIS custodian — so they ship a `redemption.json`
    (`{"receipt_id", "audience", "nonce_b64u", "sig_b64u",
    "holder_pubkey_b64u"}`) and an `expected.json` of `{"verified": bool}`.

    Every negative leaf must come back `False` rather than raise: a gate that
    fronts the delivery of content must not have an error path an attacker can
    distinguish from a refusal."""
    expected = _load_json(vector_dir / "expected.json")
    data = _load_json(vector_dir / "redemption.json")

    verified = grant.verify_redemption(
        data["receipt_id"],
        data["audience"],
        keys.b64u_decode(data["nonce_b64u"]),
        keys.b64u_decode(data["sig_b64u"]),
        data["holder_pubkey_b64u"],
    )

    assert verified == expected["verified"]


def test_vectors_directory_is_nonempty() -> None:
    """Guard against a silently-empty parametrize list (e.g. a wrong
    `VECTORS_DIR` path) making the whole suite above vacuously pass."""
    # 23 Fase 1/2 leaves (01-18) + 20 regression-corpus leaves (19-25, 2026-07-13)
    # + 8 hybrid conformance leaves (26, 2026-07-17) + 1 absent-valid_to
    # parity leaf (27, 2026-07-17) + 14 transparency/corroboration conformance
    # leaves (28, 2026-07-18) + 2 normative-ceiling leaves (29, 2026-07-22) +
    # 2 mixed-keyset leaves (30, 2026-07-22) + 5 manifest-currency leaves
    # (31, 2026-07-22) + 3 anchor-profile-v2 leaves (32, 2026-07-22, G4) +
    # 4 logged-revocation leaves (33, 2026-07-23, G5/TM-47) + 11 transfer
    # leaves (35, 2026-07-23, §17 Stage 3) + 4 transfer-chain leaves (36,
    # 2026-07-23, §17.5) + 13 witness-corroboration leaves (39, 2026-08-25,
    # §10.1/§11.4) + 20 witness-quorum leaves (40, 2026-08-25, §11.4) +
    # 23 preservation-pledge leaves (37, 2026-08-26, §18) + 4 redemption
    # leaves (38, 2026-08-26, §18.7):
    # 19 a/b, 20 a-c, 21 a-g, 22 a-c, 23 a/b, 24, 25 a/b, 26 a-h, 28 a-n,
    # 29 a/c, 30 a/b, 31 a-e, 32 a-c, 33 a-d, 35 a-k, 36 a-d, 37 a-w,
    # 38 a-d, 39 a-m, 40 a-t. Counted over
    # `_LEAF_DIRS` (ALL leaves, every surface included) — `_VECTOR_DIRS`
    # alone (the `verify()`-routed subset) excludes group 36's chain-audit
    # leaves, group 40's quorum leaves and group 38's redemption leaves.
    assert len(_LEAF_DIRS) >= 157


def test_every_leaf_is_routed_to_exactly_one_surface() -> None:
    """The four surfaces partition the corpus. Without this, a leaf shipping
    two surface files would be replayed twice, and a fifth surface file nobody
    remembered to exclude would drop out of the gate silently — which is the
    failure mode that shows up as a green suite over a truncated set."""
    assert len(_VECTOR_DIRS) + len(_CHAIN_DIRS) + len(_QUORUM_DIRS) + len(_REDEMPTION_DIRS) == len(
        _LEAF_DIRS
    )


_CANONICAL_DIRS = [p for p in _VECTOR_DIRS if (p / "canonical.json").exists()]
_CANONICAL_IDS = [str(p.relative_to(VECTORS_DIR)) for p in _CANONICAL_DIRS]


@pytest.mark.parametrize("vector_dir", _CANONICAL_DIRS, ids=_CANONICAL_IDS)
def test_payload_reserializes_to_committed_canonical_bytes(vector_dir: Path) -> None:
    """Cross-language round-trip identity, statically: the leaf ships the
    exact canonical serialization of its payload; this runner (and the TS
    conformance runner) re-serialize the parsed payload through their own
    canonical serializer and must reproduce those bytes exactly. Python
    bytes == TS bytes == committed bytes ⟹ Py→TS→Py round-trip identity
    with zero cross-runtime orchestration."""
    envelope = canon.loads_strict(_envelope_bytes(vector_dir))
    assert isinstance(envelope, dict)
    expected_bytes = (vector_dir / "canonical.json").read_bytes()
    assert canon.canonical_bytes(envelope["payload"]) == expected_bytes
