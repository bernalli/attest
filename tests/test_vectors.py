"""Replay every language-neutral attest conformance vector under
`docs/spec/vectors/` (design §11 Fase 1, generated by `tools/gen_vectors.py`).

These vectors ARE the conformance suite: any implementation, in any
language, is attest-conformant iff it reproduces every vector's `expected.json`
exactly. This test replays them through the Python reference `verify()` —
it is a genuine check, not a tautology, because `expected.json` was authored
by hand from design §6/§11 intent (see `tools/gen_vectors.py` docstrings and
the Task 10 report), not copied from whatever `verify()` happened to return.

Vector-directory conventions (a "vector case" is any directory containing
`expected.json`, discovered recursively so multi-part vectors like
`07-unicode-canon/a-...` and `09-commitment/b-...` work uniformly):

  - `envelope.json` (a normal JSON object) XOR `envelope.raw.json` (hand-
    written bytes fed to `verify()` untouched — vector 06's genuinely
    duplicated JSON member can never round-trip through `json.load`, which
    silently keeps only the last value for a repeated key).
  - `manifests.json`: `{"manifests": {...}, "provenance": {...}, "chains":
    {...}, "artifact_manifests": {...}, "artifact_manifest_chains": {...}}`,
    built directly into a `verify.TrustStore`. The last two (G2/G3, group 31
    only, attest-versioning.md rev 4) are keyed by `work.artifact_series`
    instead of issuer — every other leaf keeps them at the empty-object
    default, same convention as `chains`.
  - `expected.json`: `signature`, `schema`, `trust` (asserted exactly);
    `revocation`/`binding` (asserted exactly when present); `ok` (asserted
    exactly when present); `errors`/`warnings` (asserted as exact lists when
    present) and/or `errors_contains`/`warnings_contains` (each substring
    must appear in at least one entry).
  - optional `disclosure.json`: the §6 step 7 buyer-binding input, either
    `{"identifier", "identifier_type", "salt_b64u"}` (salt path) or
    `{"nonce_b64u", "sig_b64u"}` (challenge path).
  - optional `manifest_pristine.json`: present only for vector 11
    (manifest-tamper) — the untampered, self-consistent manifest, checked
    directly against the tampered copy in `manifests.json` via
    `manifests.verify_key_manifest()`.
  - optional `revocation.json` (Fase 2, vectors 15/16): a single issuer-signed
    revocation record, fed to `verify()` as `revocation_view=[record]`.
    Vectors 14/14b (Fase 2) need no new file — they populate `manifests.json`'s
    already-reserved `"chains"` member instead.
  - optional `transparency.json` / `log-keys.json` / `anchor-policy.json`
    (group 28 only, Stage 2 "transparency/corroboration layer"): fed to
    `verify()` as `transparency=`/`log_keys=`/`anchor_policy=`.
    `transparency.json` is the untrusted evidence bundle verbatim (see
    `attest.transparency.evaluate_transparency`'s evidence schema).
    `log-keys.json` is a list of `{"origin", "name", "ed25519_pub_b64u",
    "mldsa_pub_b64u"}`, each turned into a `tlog.LogKey`. `anchor-policy.json`
    is `{"pinned_headers": {<hex>: {"header_hash", "merkle_root", "time"}},
    "crqc_horizon"}`, turned into an `anchor.AnchorPolicy`. All three are
    absent (and `verify()` sees `None`) for every leaf outside group 28, so
    existing leaves see zero behavior change; `expected.json` only gains the
    `transparency`/`corroboration`/`manifest_freshness` members for group 28
    (and group 32).
  - optional `revocation-evidence.json` (group 33 only, v0.2 §8/§15
    amendment, G5/TM-47): fed to `verify()` as `revocation_evidence=`,
    reusing group 33's own `log-keys.json`/`anchor-policy.json` (same shape
    as group 28's). It is the untrusted transparency evidence bundle for the
    SPECIFIC `refund_window` revocation record in `revocation.json` — absent
    for every leaf outside group 33, so `verify()` sees `None` and existing
    leaves see zero behavior change. Group 33 leaves do NOT gain
    `transparency`/`corroboration`/`manifest_freshness` in `expected.json`
    (those stay at their zero-default `not_checked`/`none`/`not_checked`,
    unasserted): this is a DIFFERENT evidence channel from `transparency.json`.
  - optional `transfer-view.json` (group 35 only, v0.2 §17 Stage 3): a JSON
    ARRAY of untrusted claims `[{"record": <a transfer.py record>,
    "evidence": <§10.2 evidence bundle>}]`, fed to `verify()` as
    `transfer_view=`, reusing group 35's own `log-keys.json`/
    `anchor-policy.json`. Absent for every leaf outside group 35, so
    `verify()` sees `None`. Group 35 leaves do NOT gain `transparency`/
    `corroboration`/`manifest_freshness` either (same discipline as group 33).
  - optional `witness-policy.json` (group 39 only, v0.2 §11.4, P1.1b): the
    TRUSTED `attest-witness-policy-v1` DOCUMENT, fed to `verify()` as
    `witness_policy=`. It rides the same rail as `log-keys.json`/
    `anchor-policy.json` — verifier configuration, never evidence — which is
    why it is its own file and never appears nested inside
    `transparency.json`. The untrusted `transparency.json` names the epoch it
    claims (`witness_policy_epoch`); this document says whom that epoch pins.
    Absent for every leaf outside group 39, so `verify()` sees `None` there
    and `corroboration: "witnessed"` stays unreachable. Group 39 leaves carry
    `transparency`/`corroboration` in `expected.json`, same as group 28.
  - `witness-quorum.json` (group 40 only, v0.2 §11.4, P1.1b): a leaf
    containing this file is a THIRD surface, EXCLUDED from the `verify()`
    parametrization and from the chain-audit one, and driven instead by
    `test_witness_quorum_vectors`, which calls
    `witness.evaluate_activation_witness_quorum`. The file carries the call's
    own inputs: `expected_origin`/`conflict_domain` (TRUSTED call
    configuration, which raises when malformed) and `epoch_id`/`checkpoint`/
    `anchor_evidence` (UNTRUSTED, which may only degrade the verdict). The two
    trusted POLICIES stay in their own files, `witness-policy.json` and
    `anchor-policy.json`. There is no receipt in this group at all, so these
    leaves ship no `payload.json`/`envelope.json`/`manifests.json`; their
    `expected.json` shape is `{"valid": bool, "witness_time": int | null,
    "counting_control_groups": [...]}`, all three matched exactly.
  - optional `grant-view.json` (group 37 only, v0.2 §18 Stage 4): the
    untrusted evidence object `{"grant", "later_grants", "declarations",
    "anchor"}`, fed to `verify()` as `grant_view=`. Its PRESENCE is the
    capability gate: a leaf shipping none hands `verify()` `None`, which
    evaluates nothing at all and leaves `grant`/`grant_trust` at their
    `not_checked` defaults — which is exactly what leaf `37s`, the v0.1
    negative control, relies on. `anchor` is ONE §11 evidence bundle, never a
    list. Group 37's `expected.json` carries `grant` and `grant_trust`, the
    only group where either appears, and carries none of Stage 2's three
    (same discipline as groups 33 and 35).
  - `redemption.json` (group 38 only, v0.2 §18.7): a leaf containing this
    file is a FOURTH surface, EXCLUDED from the other three parametrizations
    and driven by `test_redemption_vectors`, which calls
    `grant.verify_redemption`. Like group 40's leaves it has no receipt in it
    at all, so it ships no `payload.json`/`envelope.json`/`manifests.json`;
    the file carries `{"receipt_id", "audience", "nonce_b64u", "sig_b64u",
    "holder_pubkey_b64u"}` and `expected.json` is `{"verified": bool}`,
    matched exactly. There is deliberately no `errors`/`warnings` on this
    surface: §18.7 forbids a gate fronting the delivery of content from
    having an error path an attacker can tell apart from a refusal.
  - `chain.json` (group 36 only, v0.2 §17.5 chain-of-title audit): a leaf
    containing this file is a SEPARATE audit surface, EXCLUDED from the
    `verify()` parametrization above and driven instead by
    `test_chain_audit_vectors`, which calls `transfer.audit_chain` with the
    leaf's `chain.json` (`{"payloads", "transfer_view", "revocation_view"}`),
    the sole trusted manifest in `manifests.json`, and `log-keys.json`/
    `anchor-policy.json`. Its `expected.json` shape is `{"chain_valid": bool,
    "link_status": [...], "errors_contains": [...], "warnings": [...]}`,
    matched as: `chain_valid` <-> `result.valid` exact, `link_status` exact
    list, `errors_contains` substring, `warnings` exact list.
"""

