def _compile_claim_shapes(
    shapes: tuple[_ClaimShape, ...],
) -> tuple[tuple[_ClaimShape, re.Pattern[str]], ...]:
    """THE one compile point, and the registry's own validator.

    Sixteen patterns were compiled one by one and not one carried IGNORECASE,
    which is why "All 97 conformance vector leaves" sailed past a guard that
    would have caught "all 97". A flag applied here cannot be forgotten by an
    entry. Making the vocabulary data also makes a malformed entry possible,
    so the registry is checked fail-closed at import: a bad entry names itself
    here rather than surfacing as an IndexError or a KeyError while scanning
    some unrelated file.
    """
    errors: list[str] = []
    seen_names: set[str] = set()
    compiled: list[tuple[_ClaimShape, re.Pattern[str]]] = []

    for shape in shapes:
        if shape.name in seen_names:
            errors.append(f"{shape.name}: duplicate claim-shape name")
        seen_names.add(shape.name)

        try:
            regex = re.compile(shape.pattern, re.IGNORECASE)
        except re.error as exc:
            errors.append(f"{shape.name}: regex does not compile: {exc}")
            continue

        if not shape.checks:
            errors.append(f"{shape.name}: has no checks")
        if shape.when_unmarked not in _WHEN_UNMARKED_VALUES:
            errors.append(
                f"{shape.name}: unknown when_unmarked {shape.when_unmarked!r} "
                f"(expected one of {sorted(_WHEN_UNMARKED_VALUES)})"
            )
        # The ambiguous branch classifies the match as a whole, from the one
        # number the sentence dates. Two checked captures have no single answer
        # here, so the registry refuses the combination rather than guessing.
        if shape.when_unmarked == "ambiguous" and len(shape.checks) != 1:
            errors.append(
                f"{shape.name}: ambiguous when_unmarked requires exactly one checked capture"
            )
        for group, key in shape.checks:
            if group < 1 or group > regex.groups:
                errors.append(f"{shape.name}: capture group {group} is outside 1..{regex.groups}")
            if key not in _CLAIM_MESSAGES:
                errors.append(f"{shape.name}: unknown measured quantity {key!r}")

        compiled.append((shape, regex))

    if errors:
        raise ValueError("corpus claim registry is not well formed: " + "; ".join(errors))
    return tuple(compiled)


_COMPILED_SHAPES = _compile_claim_shapes(_CLAIM_SHAPES)

# `\d+` will happily match thousands of digits, and int() refuses to convert a
# string past CPython's integer-string limit (4300 digits): a document with a
# long enough run of digits would abort the whole run instead of reporting a
# line. Same reflex as the non-UTF-8 branch -- report the file, keep scanning.
_MAX_CORPUS_CLAIM_DIGITS = 18


def _parse_corpus_claim_number(raw: str, rel: str, line: int) -> tuple[int | None, str | None]:
    """Parse a claimed count, or explain why it cannot be checked."""
    if len(raw) > _MAX_CORPUS_CLAIM_DIGITS:
        return None, f"{rel}:{line}: corpus claim number has too many digits to check"
    try:
        return int(raw), None
    except ValueError:
        return None, f"{rel}:{line}: corpus claim number is not parseable"


# Numbers that look like corpus claims but are not, each deliberate and each
# checked by something else. Keyed by path AND exact phrase so the exemption
# cannot widen: it excuses this sentence, not this file, and not this number
# wherever else it appears. (It does not follow that editing the line makes the
# guard fire — an earlier comment here claimed that, and a review measured it
# false: the exempt phrase is a shape no pattern matches anyway. The exemption
# is belt-and-braces against a future pattern that would.)
# Empty, and deliberately kept. Its one entry excused a `verify()`-surface
# share in verifiers/ts/README.md that the file no longer states, and that no
# pattern matched even while it did -- an exemption guarding nothing, against
# nothing. The mechanism stays as the valve for the next sentence that states a
# number the corpus does not own.
_CORPUS_CLAIM_EXEMPTIONS: dict[str, tuple[str, ...]] = {}


# Which file a leaf ships decides which surface it belongs to, and the four
# surfaces are stated as a PARTITION of the corpus: the special three are
# excluded from the verify() parametrization rather than run twice. Nothing
# in the tree enforces that, so a leaf shipping two markers is REPORTED, not
# quietly assigned. Assigning it to the first surface listed here was the
# first version, on the reasoning that the surface losing the leaf would go
# red against its stated quota: true only until somebody reconciles the
# quotas with the wrong counts, after which the guard blesses a partition
# claim that is false, forever and without a word.
_SURFACE_MARKER_FILES: tuple[tuple[str, str], ...] = (
    ("chain.json", "chain_surface"),
    ("witness-quorum.json", "quorum_surface"),
    ("redemption.json", "redemption_surface"),
)
_DEFAULT_SURFACE_KEY = "verify_surface"


class _CorpusMeasurement(NamedTuple):
    """The corpus as counted, plus what made the count untrustworthy."""

    total: int
    groups: int
    subset: int
    surfaces: dict[str, int]
    partition_errors: list[str]


def _quantities_from_corpus(measured: _CorpusMeasurement) -> dict[str, int]:
    return {
        "corpus_total": measured.total,
        "group_count": measured.groups,
        "v01_subset": measured.subset,
        **measured.surfaces,
    }


def _measured_quantities() -> dict[str, int]:
    """Every live figure a registered claim shape can be checked against."""
    return _quantities_from_corpus(_measured_corpus())


def _measured_corpus() -> _CorpusMeasurement:
    """Count the corpus on disk: (leaves, groups, v0.1 subset size, surfaces).

    Reuses `conformance_runner`'s own discovery and subset rule rather than
    restating them, so this guard cannot drift from the runner that produces
    the numbers the documents quote. The per-surface quotas come off the same
    single walk, and out of the marker files themselves -- never out of a
    hand-written share, which is the kind of number this whole check exists
    to catch.
    """
    # Imported from this file's own directory, not from _REPO_ROOT: the runner
    # is this module's sibling wherever the repository root is pointed, and
    # resolving it through _REPO_ROOT broke the moment a test pointed that at a
    # fixture tree.
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from conformance_runner import find_leaf_dirs, select_subset

    vectors_root = _REPO_ROOT / "docs/spec/vectors"
    leaves = find_leaf_dirs(vectors_root)
    groups = sorted({leaf.relative_to(vectors_root).parts[0] for leaf in leaves})
    subset = select_subset(leaves, vectors_root, "v0.1")

    surfaces = dict.fromkeys((key for _, key in _SURFACE_MARKER_FILES), 0) | {
        _DEFAULT_SURFACE_KEY: 0
    }
    partition_errors: list[str] = []
    for leaf in leaves:
        hits = [(marker, key) for marker, key in _SURFACE_MARKER_FILES if (leaf / marker).is_file()]
        if len(hits) > 1:
            rel = leaf.relative_to(vectors_root).as_posix()
            markers = ", ".join(marker for marker, _key in hits)
            partition_errors.append(f"{rel}: leaf ships multiple surface marker files: {markers}")
        key = hits[0][1] if hits else _DEFAULT_SURFACE_KEY
        surfaces[key] += 1
    return _CorpusMeasurement(len(leaves), len(groups), len(subset), surfaces, partition_errors)


def check_corpus_counts() -> list[str]:
    """Report stated corpus sizes, in known claim shapes, that the disk denies.

    Read that first line as the limit it is: this recognises the shapes it has
    been taught, listed above, and a claim phrased in a new way passes. Judging
    every figure near the corpus vocabulary instead was tried and abandoned —
    technical prose is dense with numbers beside the word "leaves" that are
    byte sizes, RFC numbers and section numbers, and that version reported 36
    of them. What actually closes this class is removing the hand-written
    numbers from the documents; that is a separate piece of work.

    Scans the tracked files of the scanned types — not a fixed list, because
    the numbers that went stale were in files nobody thought to list, and not
    the whole filesystem, because an untracked draft cannot make what ships
    drift. See `_scan_files`. Matching runs against the text with newlines
    folded to spaces: prose wraps, and the first version of this guard was
    blind to `the 52-leaf\nsubset` for exactly that reason, which its own red
    bench caught. Line numbers are recovered from the match offset so a report
    still points at the right line.

    Called directly from `main()`, like the other single-document guards.
    """
    corpus = _measured_corpus()
    quantities = _quantities_from_corpus(corpus)
    # A corpus that breaks the surface partition is reported before anything
    # is compared against it: the quotas below are only meaningful while every
    # leaf belongs to exactly one surface.
    errors: list[str] = list(corpus.partition_errors)
    # A shape may only check a quantity the registry knows how to report, and
    # the registry validator pins that at import. Nothing pinned the other
    # half: a quantity that stops being MEASURED turns the lookup below into a
    # KeyError somewhere in the middle of a scan. Name it here instead.
    unmeasured = sorted(set(_CLAIM_MESSAGES) - set(quantities))
    if unmeasured:
        errors.append(f"claim registry names quantities nothing measures: {', '.join(unmeasured)}")
        return errors
    paths, refused = _scan_files()
    errors.extend(refused)
    for path in paths:
        rel = path.relative_to(_REPO_ROOT).as_posix()
        try:
            text = path.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            # A file the gate cannot read is a file the gate is not defending.
            errors.append(f"{rel}: not valid UTF-8 -- cannot be checked for drift")
            continue
        for phrase in _CORPUS_CLAIM_EXEMPTIONS.get(rel, ()):
            text = text.replace(phrase, "")
        folded, offsets = _normalized_with_offsets(text, _COMMENT_PREFIX_BY_SUFFIX.get(path.suffix))

        def line_of(index: int, _text: str = text, _offsets: list[int] = offsets) -> int:
            return _line_number_for_offset(_text, _offsets[index])

        # Shapes overlap by design -- "130 leaf vectors across 2 groups" is
        # both a leaf-vectors claim and an across-groups one -- so the same
        # captured number would otherwise be reported once per shape that saw it.
        reported_claims: set[tuple[int, int, str]] = set()
        for shape, regex in _COMPILED_SHAPES:
            for match in regex.finditer(folded):
                line = line_of(match.start())
                if shape.when_unmarked == "ambiguous":
                    # The number this shape declares, never a hardcoded group 1:
                    # a shape whose single check reads group 2 would otherwise be
                    # classified from the wrong capture.
                    stated = match.group(shape.checks[0][0])
                    context = _sentence_around_match(folded, match.start(), match.end())
                    if _CURRENT_MARKERS.search(context):
                        pass  # a present-tense claim: fall through and compare it
                    elif _historical_bare_total_marker(context, stated):
                        continue  # an explicitly dated figure: true when written
                    else:
                        # Defaulting this to history would be the silent failure
                        # the whole check exists to prevent: an unmarked present
                        # claim would go unchecked forever, and nothing would say so.
                        errors.append(
                            f"{rel}:{line}: ambiguous bare total {stated!r} -- "
                            f"mark the sentence present-tense (it is then checked "
                            f"against the live count) or dated (it is then left alone)"
                        )
                        continue
                for group, key in shape.checks:
                    claim_id = (*match.span(group), key)
                    if claim_id in reported_claims:
                        continue
                    reported_claims.add(claim_id)
                    claimed, parse_error = _parse_corpus_claim_number(match.group(group), rel, line)
                    if parse_error is not None:
                        errors.append(parse_error)
                        continue
                    measured = quantities[key]
                    if claimed != measured:
                        errors.append(_CLAIM_MESSAGES[key](rel, line, claimed, measured))
    return errors


def _declared_version(
    path: Path, label: str, parse: Callable[[str], object], keys: tuple[str, ...]
) -> tuple[str | None, str | None]:
    """The version a package manifest declares, or why it cannot be read.

    Fail-closed by construction: an unreadable, unparsable or version-less
    manifest is reported, never raised and never quietly treated as "matches".
    A version that parses but is not a string (a JSON number, a TOML array)
    is refused too -- comparing it would report a mismatch and send the reader
    to bump a file whose real problem is its type. So is an empty one: two
    blank versions compare equal, and a check that reported "in lockstep"
    for a pair of packages neither of which declares a version would be
    exactly the silent pass this gate exists to refuse.
    """
    try:
        document: object = parse(path.read_text(encoding="utf-8"))
        for key in keys:
            document = document[key]  # type: ignore[index]
    except (OSError, ValueError, LookupError, TypeError) as exc:
        return None, f"{label}: cannot read a version to compare ({type(exc).__name__}: {exc})"
    if not isinstance(document, str):
        return None, f"{label}: cannot read a version to compare (version is not a string)"
    if not document.strip():
        return None, f"{label}: cannot read a version to compare (version is empty)"
    return document, None


def _json_loads_no_duplicate_keys(text: str) -> object:
    """`json.loads`, refusing an object that names the same member twice.

    Python keeps the LAST of a duplicated key, so a manifest declaring
    `version` twice would be read as whichever copy came last and could be
    reported "in lockstep" while being malformed. `tomllib` already refuses
    a duplicate outright, so only the JSON side needs this.
    """

    def object_pairs_hook(pairs: list[tuple[str, object]]) -> dict[str, object]:
        out: dict[str, object] = {}
        for key, value in pairs:
            if key in out:
                raise ValueError(f"duplicate JSON object member {key!r}")
            out[key] = value
        return out

    return json.loads(text, object_pairs_hook=object_pairs_hook)


def check_package_version_lockstep() -> list[str]:
    """Report the two published packages declaring different versions.

    `release.yml` already refuses to publish a tag whose version disagrees
    with either manifest, but only at the tag: between releases the two can
    drift for as long as nobody looks, and the drift surfaces as a failed
    release rather than as a failed commit. This checks it continuously.
    """
    python_version, python_error = _declared_version(
        _PYPROJECT_PATH, "pyproject.toml", tomllib.loads, ("project", "version")
    )
    ts_version, ts_error = _declared_version(
        _TS_PACKAGE_PATH,
        "verifiers/ts/package.json",
        _json_loads_no_duplicate_keys,
        ("version",),
    )
    unreadable = [error for error in (python_error, ts_error) if error is not None]
    if unreadable:
        return unreadable
    if python_version != ts_version:
        return [
            f"pyproject.toml declares version {python_version} but "
            f"verifiers/ts/package.json declares {ts_version} -- "
            f"the two registries ship in lockstep"
        ]
    return []


class _CoinedTerm(NamedTuple):
    """A term this project invented, and where a reader can learn what it means.

    Positioning surfaces come in two kinds because the rule needs a UNIT OF
    READING and only prose has one. On a Markdown surface the unit is the
    paragraph, and the term may appear as long as its paragraph glosses it.
    A structured surface -- a package manifest, HTML, the draft's XML -- has
    no such unit: split on blank lines, `package.json` is a single block, so
    "the gloss must share the paragraph" quietly becomes "the gloss must be
    somewhere in this file", which a term in `description` and a gloss three
    keys away would satisfy. Rather than pretend to a granularity the format
    does not offer, those surfaces forbid the term outright. That fails loud
    and needs no per-format parser; the day one of them must carry the term,
    the fix is to teach this module that format's unit and move the surface
    across, not to widen a rule until it stops saying anything.
    """

    name: str
    pattern: str  # regex SOURCE matching the term, never precompiled here
    defined_in: str  # repo-relative path of the defining document
    gloss_pattern: str  # must co-occur in the same paragraph, on prose surfaces
    glossable_surfaces: tuple[str, ...]  # prose: paragraph is a real unit
    term_free_surfaces: tuple[str, ...]  # structured: no unit, so no bare term either


class _CompiledCoinedTerm(NamedTuple):
    term: re.Pattern[str]
    gloss: re.Pattern[str]


_COINED_TERMS: tuple[_CoinedTerm, ...] = (
    # "Eternal verifiability" promises that the BYTES stay checkable, not that
    # the receipt stays valid: on an outsider-facing surface the bare term
    # reads as the second claim, which the project does not make. Functional
    # surfaces (SECURITY.md, CONTRIBUTING.md, the PR template, release notes)
    # are free to use it scoped by their own context; positioning surfaces
    # must gloss it in place. A link to the defining document is not a gloss:
    # it does not disambiguate the sentence the reader has landed on.
    _CoinedTerm(
        name="eternal-verifiability",
        pattern=r"\beternal[- ]verifiab\w*",
        defined_in="docs/spec/attest-versioning.md",
        gloss_pattern=r"never the ability to verify",
        glossable_surfaces=(
            "README.md",
            "docs/faq.md",
            "verifiers/ts/README.md",
        ),
        term_free_surfaces=(
            "site/index.html",
            "pyproject.toml",
            "verifiers/ts/package.json",
            "ietf/draft-bernalli-open-purchase-receipts.xml",
        ),
    ),
)


def _compile_coined_terms(terms: tuple[_CoinedTerm, ...]) -> dict[str, _CompiledCoinedTerm]:
    """THE one compile point for coined terms, and the registry's validator.

    Same construction as the claim shapes, for the same reason: a flag
    applied here cannot be forgotten by an entry, and a malformed entry names
    itself at import instead of surfacing as an obscure failure mid-scan. A
    term listing no positioning surface would defend nothing while looking
    like a defence, so the registry refuses it.
    """
    errors: list[str] = []
    compiled: dict[str, _CompiledCoinedTerm] = {}
    for term in terms:
        # The type hints on a NamedTuple bind nothing at runtime, and the
        # shapes that slip through fail LATE: a bytes pattern compiles and
        # only raises when searched against a str, halfway through a scan.
        if not isinstance(term.name, str) or not term.name:
            errors.append(f"{term.name!r}: coined-term name must be a non-empty string")
            continue
        if not isinstance(term.pattern, str):
            errors.append(f"{term.name}: term pattern must be a string")
            continue
        if not isinstance(term.gloss_pattern, str):
            errors.append(f"{term.name}: gloss pattern must be a string")
            continue
        if not isinstance(term.defined_in, str) or not term.defined_in:
            errors.append(f"{term.name}: defined_in must be a non-empty path")
        surfaces = (*term.glossable_surfaces, *term.term_free_surfaces)
        if not all(isinstance(surface, str) and surface for surface in surfaces):
            errors.append(f"{term.name}: surfaces must be non-empty strings")
        elif overlap := sorted(set(term.glossable_surfaces) & set(term.term_free_surfaces)):
            # Two rules that contradict each other on the same file; whichever
            # loop reached it first would decide, which is no rule at all.
            errors.append(
                f"{term.name}: {', '.join(overlap)} listed as both glossable and term-free"
            )
        if term.name in compiled:
            errors.append(f"{term.name}: duplicate coined-term name")
        if not surfaces:
            errors.append(f"{term.name}: has no surfaces")
        try:
            patterns = _CompiledCoinedTerm(
                re.compile(term.pattern, re.IGNORECASE),
                re.compile(term.gloss_pattern, re.IGNORECASE),
            )
        except re.error as exc:
            errors.append(f"{term.name}: regex does not compile: {exc}")
            continue
        compiled[term.name] = patterns
    if errors:
        raise ValueError("coined-term registry is not well formed: " + "; ".join(errors))
    return compiled


_COMPILED_COINED_TERMS = _compile_coined_terms(_COINED_TERMS)


# A blank line is a blank line to every reader and every renderer, whether it
# is written with CRLF, carries a stray space, or repeats. Splitting on the
# literal "\n\n" alone merged such blocks, and a gloss below then answered for
# a term above without a word being said.
_PARAGRAPH_BREAK_RE = re.compile(r"\r?\n[ \t]*(?:\r?\n)+")


def _paragraphs_with_offsets(text: str) -> list[tuple[int, str]]:
    """Blank-line-separated blocks, each with its offset in `text`."""
    blocks: list[tuple[int, str]] = []
    offset = 0
    for separator in _PARAGRAPH_BREAK_RE.finditer(text):
        blocks.append((offset, text[offset : separator.start()]))
        offset = separator.end()
    blocks.append((offset, text[offset:]))
    return blocks


def check_coined_terms() -> list[str]:
    """Coined terms on positioning surfaces must carry their gloss.

    For each registered term: the defining document must still contain it (a
    registry pointing at prose that moved on is itself drift, so that fails
    closed), and on every positioning surface each PARAGRAPH naming the term
    must also match the gloss pattern. Paragraphs are blocks split on blank
    lines; matching runs on whitespace-normalized text, so a gloss wrapped
    across lines still counts. A missing surface is skipped -- surfaces may
    legitimately disappear -- but an unreadable one is reported, because a
    surface the check cannot read is a surface it is not defending.
    """
    errors: list[str] = []
    for term in _COINED_TERMS:
        compiled = _COMPILED_COINED_TERMS[term.name]
        try:
            defining = (_REPO_ROOT / term.defined_in).read_text(encoding="utf-8")
        except UnicodeDecodeError:
            errors.append(
                f"{term.defined_in}: not valid UTF-8 -- cannot confirm it still "
                f"defines coined term '{term.name}'"
            )
            continue
        except OSError:
            errors.append(
                f"{term.defined_in}: the document defining coined term "
                f"'{term.name}' is missing -- the registry names a definition nothing ships"
            )
            continue
        folded_defining, _offsets = _normalized_with_offsets(defining, None)
        if not compiled.term.search(folded_defining):
            errors.append(
                f"{term.defined_in}: no longer states coined term '{term.name}' -- "
                f"the registry points at prose that moved on"
            )
            continue
        for surface in (*term.glossable_surfaces, *term.term_free_surfaces):
            path = _REPO_ROOT / surface
            if not path.is_file():
                continue
            try:
                text = path.read_text(encoding="utf-8")
            except UnicodeDecodeError:
                errors.append(f"{surface}: not valid UTF-8 -- cannot be checked for coined terms")
                continue
            if surface in term.term_free_surfaces:
                folded, offsets = _normalized_with_offsets(text, None)
                match = compiled.term.search(folded)
                if match is not None:
                    line = _line_number_for_offset(text, offsets[match.start()])
                    errors.append(
                        f"{surface}:{line}: coined term '{term.name}' cannot be glossed on "
                        f"this surface -- its format has no paragraph to gloss it in, so the "
                        f"term does not belong here (define-by: {term.defined_in})"
                    )
                continue
            for block_offset, block in _paragraphs_with_offsets(text):
                folded, offsets = _normalized_with_offsets(block, None)
                match = compiled.term.search(folded)
                if match is None or compiled.gloss.search(folded):
                    continue
                line = _line_number_for_offset(text, block_offset + offsets[match.start()])
                errors.append(
                    f"{surface}:{line}: coined term '{term.name}' appears on a "
                    f"positioning surface without its gloss (define-by: {term.defined_in})"
                )
    return errors


def collect_errors(
    threat_model: str,
    privacy: str,
    spec_v01: str,
    spec_v02: str,
    schema: dict[str, object],
    versioning: str,
) -> list[str]:
    """Cross-check the two companion docs against each other and the specs.

    Also checks attest-versioning.md's required sections and registries, and
    that both normative specs carry the `## Revision log` section its
    amendment procedure (§5) requires.

    Returns one human-readable string per problem found; an empty list means
    the documents are internally consistent and in sync with the specs and
    schema they cite.
    """
    # Illustrative tables and sample entries live in code fences throughout both
    # documents. They read exactly like the real thing, so scanning them would let
    # a fenced example stand in for a real matrix row or catalog entry.
    threat_model = _strip_fenced_blocks(threat_model)
    privacy = _strip_fenced_blocks(privacy)

    headings_v01 = parse_headings(spec_v01)
    headings_v02 = parse_headings(spec_v02)
    tm_entries = _parse_tm_entries(threat_model)
    tm_ids = [entry.tm_id for entry in tm_entries]
    pc_rows = parse_pc_rows(privacy)

    errors: list[str] = []
    errors += [f"attest-threat-model.md: {e}" for e in check_ids(tm_ids)]
    errors += [f"attest-threat-model.md: {e}" for e in check_verdicts(tm_entries)]
    errors += [
        f"attest-threat-model.md: {e}"
        for e in check_spec_refs(tm_entries, headings_v01, headings_v02)
    ]
    errors += [f"attest-threat-model.md: {e}" for e in check_matrix(threat_model, set(tm_ids))]
    errors += [f"attest-privacy.md: {e}" for e in check_claims(pc_rows)]
    errors += [f"attest-privacy.md: {e}" for e in check_schema_pins(pc_rows, schema)]
    errors += [f"attest-privacy.md: {e}" for e in check_pc08_corpus_claim(pc_rows, _VECTORS_PATH)]
    errors += [f"attest-versioning.md: {e}" for e in check_versioning_sections(versioning)]
    errors += [f"attest-versioning.md: {e}" for e in check_versioning_suite_names(versioning)]
    errors += [f"attest-versioning.md: {e}" for e in check_versioning_lifecycle_states(versioning)]
    errors += [
        f"attest-versioning.md: {e}" for e in check_versioning_revocation_classes(versioning)
    ]
    errors += [
        f"attest-versioning.md: {e}" for e in check_versioning_lifecycle_exception(versioning)
    ]
    errors += [
        f"attest-versioning.md: {e}" for e in check_versioning_transfer_registries(versioning)
    ]
    errors += check_v02_stage3_transfer_profile(spec_v02)
