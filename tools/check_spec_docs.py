def _scan_files() -> tuple[list[Path], list[str]]:
    """Files the textual-drift checks scan, plus entries refused out loud.

    `git ls-files` when the root is a checkout; a deterministic rglob fallback
    otherwise (source tarball, test fixture tree), which is the pre-existing
    behavior widened to the same suffix set. Entries are sorted, filtered to
    the scanned types, and must still exist on disk.

    A scanned-suffix entry that is a symlink is REFUSED rather than followed:
    `is_file()` resolves the target, so a link could pull text from outside
    the repository into the perimeter, or vanish silently when dangling. A
    gitlink (submodule) is not a regular file and drops out here. An unstaged
    rename shows up as a deleted tracked path plus an untracked new one, so
    the new surface is unscanned locally until the rename is staged -- absent
    in CI, whose checkout is always consistent.
    """
    try:
        git = shutil.which("git")
        if git is None:
            raise OSError("git is not on PATH")
        # `git -C X ls-files` succeeds from ANYWHERE inside a checkout and
        # lists only what is under X: a tree nested in an unrelated repository
        # would hand back an empty perimeter and the gate would exit clean
        # having defended nothing. Only the repository root may use the index.
        top = subprocess.run(  # noqa: S603 -- fixed argv list, no shell
            [git, "-C", str(_REPO_ROOT), "rev-parse", "--show-toplevel"],
            capture_output=True,
            text=True,
            errors="surrogateescape",
            check=True,
            timeout=30,
        )
        if Path(top.stdout.rstrip("\n")).resolve() != _REPO_ROOT.resolve():
            raise OSError(f"{_REPO_ROOT} is not the git repository root")
        proc = subprocess.run(  # noqa: S603 -- fixed argv list, no shell
            [git, "-C", str(_REPO_ROOT), "ls-files", "-z"],
            capture_output=True,
            text=True,
            errors="surrogateescape",  # a non-UTF-8 path must not crash the gate
            check=True,
            timeout=30,
        )
        names = [name for name in proc.stdout.split("\0") if name]
    except (OSError, subprocess.SubprocessError):
        names = [
            path.relative_to(_REPO_ROOT).as_posix()
            for suffix in _SCAN_SUFFIXES
            for path in _REPO_ROOT.rglob(f"*{suffix}")
        ] + [
            path.relative_to(_REPO_ROOT).as_posix()
            for base in _SCAN_MANIFEST_BASENAMES
            for path in _REPO_ROOT.rglob(base)
        ]
    selected: list[Path] = []
    refused: list[str] = []
    for name in sorted(set(names)):
        basename = name.rsplit("/", 1)[-1]
        if not (name.endswith(_SCAN_SUFFIXES) or basename in _SCAN_MANIFEST_BASENAMES):
            continue
        if "node_modules" in name or name.startswith(".git/"):
            continue
        # The changelog records what the numbers WERE; that is its job.
        if name.endswith("CHANGELOG.md") or name in _SCAN_EXCLUDED_FILES:
            continue
        path = _REPO_ROOT / name
        if path.is_symlink():
            refused.append(f"{name}: symlink in the scan perimeter -- refused, not followed")
            continue
        if path.is_file():
            selected.append(path)
    return selected, refused


# Which line-comment marker to strip, per scanned suffix. A quota that wraps
# onto a second comment line puts the marker INSIDE the phrase, where no
# pattern can see past it. `.html` has no line comment, and `.md` needs none.
_COMMENT_PREFIX_BY_SUFFIX: dict[str, str] = {".py": "#", ".ts": "//"}


def _normalized_with_offsets(text: str, comment_prefix: str | None) -> tuple[str, list[int]]:
    """Collapse whitespace runs to single spaces, optionally stripping a
    line-comment marker at each line start, and map every normalized
    character back to its offset in the original text.

    Prose wraps and comments wrap harder: a phrase split across two `//`
    lines is invisible to any single-line or fold-preserving search. The
    offset map is what keeps reported line numbers honest after the text
    has been reshaped.
    """
    out: list[str] = []
    offsets: list[int] = []
    pending_space_offset: int | None = None
    position = 0
    for raw_line in text.splitlines(keepends=True):
        line_start = position
        position += len(raw_line)
        stripped = raw_line.lstrip()
        lead = len(raw_line) - len(stripped)
        if lead and pending_space_offset is None:
            pending_space_offset = line_start
        if comment_prefix is not None and stripped.startswith(comment_prefix):
            lead += len(comment_prefix)
            stripped = stripped[len(comment_prefix) :]
        for index, char in enumerate(stripped):
            original_offset = line_start + lead + index
            if char.isspace():
                # Remember where the run STARTED: a collapsed space that
                # points at the character after it reports the wrong line.
                if pending_space_offset is None:
                    pending_space_offset = original_offset
                continue
            if pending_space_offset is not None and out:
                out.append(" ")
                offsets.append(pending_space_offset)
            pending_space_offset = None
            out.append(char)
            offsets.append(original_offset)
    return "".join(out), offsets


def _line_number_for_offset(text: str, original_offset: int) -> int:
    """The 1-based line an offset falls on.

    Counts the boundaries `splitlines` counts, not just "\\n": normalization
    already treats U+2028 and friends as line ends, and a report that
    disagreed would name a line the reader cannot find. Shared by every check
    that reports a position through the offset map, so the two cannot drift.
    """
    position = 0
    for line_number, raw_line in enumerate(text.splitlines(keepends=True), 1):
        position += len(raw_line)
        if original_offset < position:
            return line_number
    return 1


